export type MessageId = keyof typeof enMessages;

/** A plural group: the key without its `.one` or `.other`. */
export type PluralId = {
	[K in MessageId]: K extends `${infer Base}.one` ? Base : never;
}[MessageId];

function interpolate(message: string, values: Record<string, string | number> | undefined): string {
	if (!values) return message;
	return message.replace(/\{(\w+)\}/g, (token, name: string) =>
		name in values ? String(values[name]) : token,
	);
}

/** The message for `id` in the active catalogue, or English when that catalogue lacks it. */
export function t(id: MessageId, values?: Record<string, string | number>): string {
	return interpolate((activeMessages() as Record<string, string>)[id] ?? enMessages[id], values);
}

/**
 * The message for `count` of something, in the plural form the locale's rules choose. A form
 * neither the catalogue nor English spells out uses `.other`. `{count}` is replaced with the number
 * formatted for the locale.
 */
export function tn(
	id: PluralId,
	count: number,
	values: Record<string, string | number> = {},
): string {
	const form = new Intl.PluralRules(pluralLocale()).select(count);
	const exact = `${id}.${form}`;
	const own = activeMessages() as Record<string, string | undefined>;
	const english = enMessages as Record<string, string>;
	const key = exact in english || exact in own ? exact : `${id}.other`;
	const message = own[key] ?? english[key] ?? key;
	const formatted = new Intl.NumberFormat(formatLocale()).format(count);
	return interpolate(message, { ...values, count: formatted });
}
