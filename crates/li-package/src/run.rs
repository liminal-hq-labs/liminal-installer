//! The stub verifies the payload's SHA-256 when a hashing tool is present, extracts it to a
//! prefix (`/opt/<slug>` as root, `$XDG_DATA_HOME/<slug>` otherwise, or `--prefix`), and then
//! runs the project's engine from the payload with `install --from <prefix>` when the
//! package names one. Options: `--prefix DIR`, `--list`, `--check`, `--noexec`, `--help`, and
//! `--` to pass the rest to the engine.
//!
//! [`build_engine`] writes the themed form: the archive holds only the engine and the files it
//! needs (no receipt), and the engine makes the install, so the receipt records what it did.

use std::path::Path;

use crate::info::Entry;
use crate::info::PackageInfo;
use crate::payload::{entries_tar_gz, payload_tar_gz};
use crate::xml::{sh_quote, sha256_hex};
use crate::{PackageError, Result};

const STUB: &str = r#"#!/bin/sh
# Self-extracting installer for @NAME_COMMENT@ @VERSION_COMMENT@.
# Generated by liminst. The payload follows the stub, from line PAYLOAD_LINE.
set -eu

PRODUCT=@NAME@
VERSION=@VERSION@
SLUG=@SLUG@
SHA256=@SHA256@
ENGINE=@ENGINE@
PAYLOAD_LINE=@LINE@

die() {
	echo "$0: $*" >&2
	exit 1
}

usage() {
	cat <<EOF
$PRODUCT $VERSION installer

Usage: sh $0 [options]

Options:
  --prefix DIR  Install into DIR (default: /opt/$SLUG as root, otherwise
                \${XDG_DATA_HOME:-\$HOME/.local/share}/$SLUG)
  --list        List the files in the payload and exit
  --check       Verify the payload checksum and exit
  --noexec      Extract only; do not run the installer engine
  -h, --help    Show this help
  --            Pass everything after it to the installer engine
EOF
}

payload() {
	tail -n "+$PAYLOAD_LINE" "$0"
}

checksum() {
	if command -v sha256sum >/dev/null 2>&1; then
		payload | sha256sum | cut -d ' ' -f 1
	elif command -v shasum >/dev/null 2>&1; then
		payload | shasum -a 256 | cut -d ' ' -f 1
	elif command -v sha256 >/dev/null 2>&1; then
		payload | sha256 -q
	else
		echo ""
	fi
}

verify() {
	sum=$(checksum)
	if [ -z "$sum" ]; then
		echo "warning: no SHA-256 tool found; skipping the integrity check" >&2
	elif [ "$sum" != "$SHA256" ]; then
		die "the payload is damaged (checksum mismatch)"
	fi
}

prefix=
list=0
check=0
noexec=0
while [ "$#" -gt 0 ]; do
	case "$1" in
	--prefix)
		[ "$#" -ge 2 ] || die "--prefix needs a directory"
		prefix=$2
		shift 2
		;;
	--prefix=*)
		prefix=${1#--prefix=}
		shift
		;;
	--list)
		list=1
		shift
		;;
	--check)
		check=1
		shift
		;;
	--noexec)
		noexec=1
		shift
		;;
	-h | --help)
		usage
		exit 0
		;;
	--)
		shift
		break
		;;
	*)
		die "unknown option: $1 (try --help)"
		;;
	esac
done

if [ "$list" = 1 ]; then
	payload | tar -tzf -
	exit 0
fi

verify
if [ "$check" = 1 ]; then
	echo "Checksum ok."
	exit 0
fi

if [ -z "$prefix" ]; then
	if [ "$(id -u)" = 0 ]; then
		prefix=/opt/$SLUG
	else
		prefix=${XDG_DATA_HOME:-$HOME/.local/share}/$SLUG
	fi
fi

mkdir -p "$prefix" || die "cannot create $prefix"
payload | tar -xzf - -C "$prefix" || die "extraction failed"

if [ -n "$ENGINE" ] && [ "$noexec" = 0 ] && [ -x "$prefix/$ENGINE" ]; then
	exec "$prefix/$ENGINE" install --from "$prefix" "$@"
fi
echo "$PRODUCT $VERSION extracted to $prefix"
exit 0
"#;

/// The stub for `info`, with the checksum and payload offset filled in.
pub fn stub(info: &PackageInfo, payload_sha256: &str) -> String {
	let fill = |line: &str| {
		STUB.replace("@NAME_COMMENT@", &info.name.replace(['\n', '\r'], " "))
			.replace(
				"@VERSION_COMMENT@",
				&info.version.replace(['\n', '\r'], " "),
			)
			.replace("@NAME@", &sh_quote(&info.name))
			.replace("@VERSION@", &sh_quote(&info.version))
			.replace("@SLUG@", &sh_quote(&info.slug()))
			.replace("@SHA256@", &sh_quote(payload_sha256))
			.replace("@ENGINE@", &sh_quote(info.engine.as_deref().unwrap_or("")))
			.replace("@LINE@", line)
	};
	// The offset has a fixed width, so the stub's line count does not depend on it.
	let lines = fill("00000").lines().count();
	fill(&format!("{:05}", lines + 1))
}

/// The complete `.run`: stub bytes followed by the payload archive.
pub fn assemble(info: &PackageInfo) -> Result<Vec<u8>> {
	let payload = payload_tar_gz(info, None)?;
	let mut out = stub(info, &sha256_hex(&payload)).into_bytes();
	out.extend_from_slice(&payload);
	Ok(out)
}

/// The complete `.run` for an engine-driven install: `entries` replace the product files and no
/// receipt is added. `info.engine` must name one of the entries.
pub fn assemble_engine(info: &PackageInfo, entries: &[Entry]) -> Result<Vec<u8>> {
	let payload = entries_tar_gz(entries, None)?;
	let mut out = stub(info, &sha256_hex(&payload)).into_bytes();
	out.extend_from_slice(&payload);
	Ok(out)
}

/// Writes the `.run` to `out` and marks it executable.
pub fn build(info: &PackageInfo, out: &Path) -> Result<()> {
	write_executable(&assemble(info)?, out)
}

/// Writes the engine-driven `.run` to `out` and marks it executable.
pub fn build_engine(info: &PackageInfo, entries: &[Entry], out: &Path) -> Result<()> {
	write_executable(&assemble_engine(info, entries)?, out)
}

fn write_executable(bytes: &[u8], out: &Path) -> Result<()> {
	if let Some(dir) = out.parent() {
		std::fs::create_dir_all(dir).map_err(|e| PackageError::io(dir, e))?;
	}
	std::fs::write(out, bytes).map_err(|e| PackageError::io(out, e))?;
	#[cfg(unix)]
	{
		use std::os::unix::fs::PermissionsExt;
		std::fs::set_permissions(out, std::fs::Permissions::from_mode(0o755))
			.map_err(|e| PackageError::io(out, e))?;
	}
	Ok(())
}
